#!/usr/bin/env python3
"""Extract the traces of RFC 8448 (Example Handshake Traces for TLS 1.3).

Development-time tool. Usage:

    tools/rfc8448.py spec/rfc/rfc8448.txt > tests/vectors/rfc8448.txt

Writes one value per line, tab-separated:

    <section> <step> <occurrence> <name> <hex>

where <step> is the step's title as the RFC prints it (for example
`{server}  derive secret "tls13 c hs traffic":`), <occurrence> counts steps
with the same title in the section from 1, and <name> is the value's label
(for example `expanded`). Only sections 3 (simple 1-RTT handshake) and 5
(HelloRetryRequest) are extracted.
"""
import re
import sys

SECTIONS = {"3": "Simple 1-RTT Handshake", "5": "HelloRetryRequest"}

def main():
    lines = open(sys.argv[1]).read().splitlines()
    out = ["# Generated by tools/rfc8448.py from RFC 8448. Do not edit.",
           "# <section>\t<step>\t<occurrence>\t<name>\t<hex>"]
    section = None
    step = None
    seen = {}
    name = None
    value = []

    def flush():
        nonlocal name, value
        if name is not None and section in SECTIONS:
            out.append("\t".join([section, step, str(seen[(section, step)]), name, "".join(value)]))
        name, value = None, []

    for line in lines:
        if line.startswith("RFC 8448") or re.match(r"^Thomson\s.*\[Page \d+\]$", line) or not line.strip():
            continue
        heading = re.match(r"^(\d+)\.  (.*)$", line)
        if heading:
            flush()
            section = heading.group(1)
            continue
        if line.startswith("   {"):
            flush()
            step = line.strip()
            seen[(section, step)] = seen.get((section, step), 0) + 1
            continue
        labelled = re.match(r"^      (\S.*?) \((\d+) octets\):  (.*)$", line)
        if labelled:
            flush()
            name = labelled.group(1)
            rest = labelled.group(3)
            value = [] if rest == "(empty)" else [rest.replace(" ", "")]
            continue
        if name is not None and re.match(r"^\s+([0-9a-f]{2} ?)+$", line):
            value.append(line.strip().replace(" ", ""))
            continue
        flush()
    flush()
    print("\n".join(out))

main()
